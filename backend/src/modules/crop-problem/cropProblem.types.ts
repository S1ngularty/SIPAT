import type { Types } from "mongoose";

// ==========================================
// ENUMS / UNION TYPES
// ==========================================

export const CROP_PROBLEM_TYPES = ["disease", "pest", "healthy"] as const;
export type CropProblemType = (typeof CROP_PROBLEM_TYPES)[number];

/**
 * Practical risk guidance. `low` / `medium` / `high` describe how much damage
 * the problem can cause if left unmanaged.
 */
export const CROP_PROBLEM_SEVERITIES = ["low", "medium", "high"] as const;
export type CropProblemSeverity = (typeof CROP_PROBLEM_SEVERITIES)[number];

/** Editorial state of a reference record. */
export const CROP_PROBLEM_REVIEW_STATUSES = [
  "draft",
  "pending",
  "reviewed",
  "approved",
  "deprecated",
] as const;
export type CropProblemReviewStatus =
  (typeof CROP_PROBLEM_REVIEW_STATUSES)[number];

/** Plant organs a problem can affect. */
export const CROP_PROBLEM_AFFECTED_PARTS = [
  "leaves",
  "stems",
  "roots",
  "flowers",
  "fruits",
] as const;
export type CropProblemAffectedPart =
  (typeof CROP_PROBLEM_AFFECTED_PARTS)[number];

// ==========================================
// EMBEDDED SHAPES
// ==========================================

/** Bilingual explanation. `tl` is Tagalog, `en` is English. */
export interface LocalizedText {
  tl: string;
  en: string;
}

/**
 * A treatment grouping. `category` is a broad class (e.g. "fungicide",
 * "biological control", "cultural"), `examples` lists product or practice
 * names, and `cautions` captures label/PHI/rotation warnings.
 */
export interface CropProblemTreatment {
  category: string;
  examples: string[];
  cautions: string[];
}

/** PPE, environmental precautions, and pre-harvest interval notes. */
export interface CropProblemSafety {
  ppe: string[];
  environmentalPrecautions: string[];
  harvestRestrictions: string;
}

/** A reference/evidence image or diagram. */
export interface CropProblemMedia {
  url: string;
  /** Free-form kind, e.g. `reference`, `evidence`, `diagram`. */
  type: string;
  caption: string;
}

/** Provenance and editorial metadata for a reference record. */
export interface CropProblemMetadata {
  version: string;
  sources: string[];
  reviewDate: Date | null;
  reviewStatus: CropProblemReviewStatus;
}

// ==========================================
// DOMAIN MODEL
// ==========================================

export interface CropProblem {
  _id: Types.ObjectId;

  /** Stable, unique, human-authored record ID (e.g. `tomato-late-blight`). */
  id: string;

  /** Machine-friendly identifier used in URLs and lookups. */
  slug: string;

  /** Display name in English. */
  name: string;

  /** Tagalog / common Filipino name, when established. */
  localName: string;

  type: CropProblemType;

  /** Broad class, e.g. `fungal`, `bacterial`, `viral`, `insect`, `mite`. */
  category: string;

  /** Organism or pathogen name, when known. */
  scientificName: string;

  description: LocalizedText;

  /** Crop IDs/slugs affected by the problem (e.g. `tomato`, `eggplant`). */
  affectedCrops: string[];

  affectedParts: CropProblemAffectedPart[];

  /** Visible signs and damage. */
  symptoms: string[];

  /** Conditions that encourage the problem. */
  favorableConditions: string[];

  /** How it spreads, or how the pest moves. */
  transmission: string[];

  severity: CropProblemSeverity;

  /** Similar-looking problems that may be confused with it. */
  differentialDiagnosis: string[];

  /** Prevention and non-chemical management. */
  management: string[];

  /** Treatment categories and cautions. */
  treatments: CropProblemTreatment[];

  /** Commands/IDs pointing to `agricultural_actions`. */
  actionRefs: string[];

  safety: CropProblemSafety;

  /** What the AI should check before reporting a match. */
  diagnosisGuidance: string[];

  /** Reference image URLs, evidence images, or diagrams. */
  media: CropProblemMedia[];

  metadata: CropProblemMetadata;

  createdAt: Date;
  updatedAt: Date;
}

// ==========================================
// CREATE / UPDATE TYPES
// ==========================================

/**
 * Fields required to create a record. Timestamps and the Mongo `_id` are
 * generated by the database.
 */
export type CreateCropProblemInput = Omit<
  CropProblem,
  "_id" | "createdAt" | "updatedAt"
>;

/** Every updatable field is optional. `| undefined` keeps it assignable under
 * `exactOptionalPropertyTypes` when a parser emits explicit `undefined`. */
export type UpdateCropProblemInput = {
  [K in keyof CreateCropProblemInput]?:
    | CreateCropProblemInput[K]
    | undefined;
};

// ==========================================
// FILTER / QUERY TYPES
// ==========================================

export interface CropProblemFilter {
  type?: CropProblemType;
  severity?: CropProblemSeverity;
  category?: string;
  affectedCrops?: string[];
  affectedParts?: CropProblemAffectedPart[];
  reviewStatus?: CropProblemReviewStatus;
  /** Case-insensitive match against name/slug/localName/scientificName. */
  search?: string;
}

export type CropProblemSortField =
  | "createdAt"
  | "updatedAt"
  | "name"
  | "severity";

export interface CropProblemListOptions {
  page?: number;
  limit?: number;
  sortBy?: CropProblemSortField;
  sortOrder?: "asc" | "desc";
  filter?: CropProblemFilter;
}

export interface CropProblemListResult {
  data: CropProblem[];
  total: number;
  page: number;
  limit: number;
  totalPages: number;
}

/** Result summary returned by the bulk seeding/upsert path. */
export interface CropProblemBulkUpsertResult {
  matched: number;
  modified: number;
  upserted: number;
  total: number;
}
